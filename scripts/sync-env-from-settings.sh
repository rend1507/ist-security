#!/usr/bin/env bash
# Buat .env + .dev.vars dari settings/cloudflare/.env
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORKSPACE="$(cd "$ROOT/../../../.." && pwd)"
CF_ENV="$WORKSPACE/settings/cloudflare/.env"
TARGET="$ROOT/.env"
DEV_VARS="$ROOT/.dev.vars"
WRANGLER="$ROOT/wrangler.jsonc"
DEPLOY_SECRET="$ROOT/.deploy-session-secret"

if [[ ! -f "$CF_ENV" ]]; then
  echo "ERROR: $CF_ENV tidak ada."
  exit 1
fi

export CF_ENV TARGET DEV_VARS WRANGLER DEPLOY_SECRET

python3 <<'PY'
import os, re
from pathlib import Path

def load_env(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if not path.exists():
        return out
    for line in path.read_text().splitlines():
        raw = line.strip()
        if not raw or raw.startswith("#") or "=" not in raw:
            continue
        k, v = raw.split("=", 1)
        v = v.strip()
        if len(v) >= 2 and ((v[0] == v[-1] == '"') or (v[0] == v[-1] == "'")):
            v = v[1:-1]
        out[k.strip()] = v
    return out

def q(v: str) -> str:
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'

cf = load_env(Path(os.environ["CF_ENV"]))
if not cf.get("CLOUDFLARE_API_TOKEN"):
    raise SystemExit("ERROR: CLOUDFLARE_API_TOKEN kosong")

existing = load_env(Path(os.environ["TARGET"]))
dev = load_env(Path(os.environ["DEV_VARS"]))
session = (
    existing.get("SESSION_SECRET")
    or dev.get("SESSION_SECRET")
    or (Path(os.environ["DEPLOY_SECRET"]).read_text().strip() if Path(os.environ["DEPLOY_SECRET"]).exists() else "")
    or "ist-security-dev-secret-change-me"
)

d1 = "a4c49041-ace2-4b5b-8ae5-29726a6893a4"
wrangler = Path(os.environ["WRANGLER"])
if wrangler.exists():
    m = re.search(r'"database_id"\s*:\s*"([^"]+)"', wrangler.read_text())
    if m:
        d1 = m.group(1)

rows = [
    "# IST Security — generated by scripts/sync-env-from-settings.sh",
    "# Jangan commit. Sumber CF: settings/cloudflare/.env",
    "",
    f"APP_NAME={q('IST Security')}",
    "DEFAULT_OVERDUE_MINUTES=5",
    f"SESSION_SECRET={q(session)}",
    "",
    "CLOUDFLARE_WORKER_NAME=ist-security",
    "D1_DATABASE_NAME=ist-security",
    f"D1_DATABASE_ID={d1}",
    "",
    f"CLOUDFLARE_ACCOUNT_ID={q(cf.get('CLOUDFLARE_ACCOUNT_ID', ''))}",
    f"CLOUDFLARE_API_TOKEN={q(cf.get('CLOUDFLARE_API_TOKEN', ''))}",
    f"CLOUDFLARE_EMAIL={q(cf.get('CLOUDFLARE_EMAIL', ''))}",
    "",
]

target = Path(os.environ["TARGET"])
target.write_text("\n".join(rows))
target.chmod(0o600)

Path(os.environ["DEV_VARS"]).write_text(
    "\n".join(
        [
            f"SESSION_SECRET={q(session)}",
            f"APP_NAME={q('IST Security')}",
            "DEFAULT_OVERDUE_MINUTES=5",
            "",
        ]
    )
)
Path(os.environ["DEV_VARS"]).chmod(0o600)
print(f"OK: {target}")
print(f"OK: {os.environ['DEV_VARS']}")
print("Nilai secret tidak ditampilkan.")
PY
